CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE accounts (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT        NOT NULL REFERENCES users(id),
    name     VARCHAR(100)  NOT NULL,
    balance  NUMERIC(19,2) NOT NULL DEFAULT 0,
    CONSTRAINT uk_account_user_name UNIQUE (user_id, name)
);

CREATE TABLE categories (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT       NOT NULL REFERENCES users(id),
    name     VARCHAR(100) NOT NULL,
    CONSTRAINT uk_category_user_name UNIQUE (user_id, name)
);

CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users(id),
    account_id  BIGINT        NOT NULL REFERENCES accounts(id),
    category_id BIGINT        NOT NULL REFERENCES categories(id),
    type        VARCHAR(10)   NOT NULL CHECK (type IN ('INCOME','EXPENSE')),
    amount      NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    tx_date     DATE          NOT NULL,
    ym          VARCHAR(7)    NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_tx_user_date ON transactions (user_id, tx_date);
CREATE INDEX idx_tx_user_ym   ON transactions (user_id, ym);
CREATE INDEX idx_tx_account   ON transactions (account_id);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id),
    token_hash VARCHAR(64)  NOT NULL UNIQUE,
    family_id  VARCHAR(36)  NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_rt_family ON refresh_tokens (family_id);
CREATE INDEX idx_rt_user   ON refresh_tokens (user_id);

CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    entity_type VARCHAR(50)  NOT NULL,
    entity_id   BIGINT,
    action      VARCHAR(30)  NOT NULL,
    details     VARCHAR(2000),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_user_time ON audit_events (user_id, created_at);

